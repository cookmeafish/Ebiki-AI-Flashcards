// Runs as `postinstall` (package.json) after every `npm install`. Gives the Electron app window
// its own icon on the Windows taskbar/Start Menu/Alt-Tab, not the generic Electron logo.
//
// Why this is needed at all: electron/main.cjs's BrowserWindow `icon` option only sets the
// WINDOW's own icon (title bar, taskbar button while running) - it does NOT change what Windows
// shows for a PINNED taskbar shortcut. Since this app runs unpackaged, straight out of
// node_modules/electron/dist/electron.exe (no electron-builder/electron-packager step - that
// would fight the live-reload dev workflow this whole project is built around), the actual
// running binary IS the stock Electron.exe, icon and all - and "pin to taskbar" on Windows
// resolves the pinned icon from the EXE FILE ITSELF, ignoring the runtime BrowserWindow.icon
// entirely, unless there's a matching registered shortcut with its own icon (there isn't one for
// a dev-run exe). This is a well-known Electron dev-mode gotcha, not specific to this app.
//
// Fix: make a COPY of electron.exe named Ebiki.exe with ebiki.ico baked into its own PE resources
// via rcedit (the same tool electron-packager itself uses internally for this exact purpose) -
// launch.ps1's Open-App prefers this copy over the plain electron.exe. Living inside
// node_modules/electron/dist/ means it's never git-tracked and is naturally regenerated by this
// same postinstall step whenever electron itself is reinstalled/updated (keeping it in sync
// without any extra bookkeeping).
//
// Fail-soft everywhere, matching electron's own optionalDependency status: any failure here
// (electron not installed, rcedit not installed, wrong platform, rcedit itself erroring) is
// logged and swallowed, never failing `npm install`. Windows-only - Linux's taskbar/dock icon is
// already handled correctly via scripts/setup.sh's .desktop entry (Icon= + StartupWMClass), which
// doesn't have this problem since it never depends on the running binary's own baked-in icon.
import { existsSync, copyFileSync } from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

async function main() {
  if (process.platform !== 'win32') return

  const electronExe = path.join(appRoot, 'node_modules', 'electron', 'dist', 'electron.exe')
  if (!existsSync(electronExe)) {
    console.log('[brand-electron-exe] electron.exe not found (electron is optional) - skipping')
    return
  }
  const icon = path.join(appRoot, 'ebiki.ico')
  if (!existsSync(icon)) {
    console.log('[brand-electron-exe] ebiki.ico not found - skipping')
    return
  }

  let rcedit
  try {
    ;({ rcedit } = await import('rcedit'))
  } catch {
    console.log('[brand-electron-exe] rcedit not installed (optional) - skipping, taskbar icon will be the generic Electron logo')
    return
  }

  const brandedExe = path.join(appRoot, 'node_modules', 'electron', 'dist', 'Ebiki.exe')
  try {
    copyFileSync(electronExe, brandedExe)
    await rcedit(brandedExe, {
      icon,
      'version-string': { ProductName: 'Ebiki', FileDescription: 'Ebiki' },
    })
    console.log('[brand-electron-exe] Ebiki.exe created with the Ebi icon.')
  } catch (err) {
    console.log('[brand-electron-exe] failed to brand the exe (falling back to the generic Electron icon):', err.message)
  }
}

main()
