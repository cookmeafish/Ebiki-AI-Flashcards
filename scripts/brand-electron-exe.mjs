// Runs as `postinstall` (package.json) after every `npm install`. Makes the raw Electron binary in
// node_modules actually BEHAVE like Ebiki instead of generic Electron - two separate fixes, both
// needed because this app runs unpackaged straight out of node_modules/electron/dist/electron.exe
// (no electron-builder/electron-packager step, which would fight the live-reload dev workflow this
// whole project is built around):
//
// 1) ICON. electron/main.cjs's BrowserWindow `icon` option only sets the WINDOW's own icon (title
//    bar, taskbar button while running) - it does NOT change what Windows shows for a PINNED
//    taskbar shortcut, which Windows resolves from the EXE FILE ITSELF, ignoring the runtime
//    option entirely (there's no matching registered shortcut with its own icon for a dev-run
//    exe). Fixed by making a COPY of electron.exe named Ebiki.exe with ebiki.ico baked into its
//    own PE resources via rcedit - the same tool electron-packager itself uses internally for
//    this. scripts/launch.ps1's Open-App prefers this copy.
//
// 2) BARE LAUNCH. Pinning that same running window to the taskbar (right-click the taskbar
//    button -> Pin) only remembers the EXE PATH, not the command-line arguments it was launched
//    with - Windows has no registered shortcut to fall back to for an unpackaged exe. Launching
//    Ebiki.exe/electron.exe with NO arguments at all is exactly what a plain `electron` (no path)
//    does: show Electron's own bundled getting-started demo screen instead of Ebiki (reported as
//    "still turns into electron picture"). Electron's app-resolution ALSO checks a fixed
//    convention path relative to the exe - `<exe_dir>/resources/app/` (a folder with its own
//    package.json) - before falling back to that demo screen; this is exactly the layout a REAL
//    packaged app has, so mirroring it here makes a bare, argument-less launch resolve correctly
//    too. Verified live: `electron.exe` with zero arguments loads and runs Ebiki normally once
//    resources/app/package.json exists.
//
// Both live inside node_modules/electron/dist/ - never git-tracked, and regenerated by this same
// postinstall step whenever electron itself is reinstalled or updated, with no extra bookkeeping.
//
// Fail-soft throughout, matching electron's own optionalDependency status: any failure here
// (electron not installed, rcedit not installed, wrong platform, rcedit itself erroring) is logged
// and swallowed, never failing `npm install`. Windows-only - Linux's taskbar/dock icon is already
// handled correctly via scripts/setup.sh's .desktop entry (Icon= + StartupWMClass), and a bare
// `electron` launch on Linux isn't a real scenario here (scripts/launch.sh always passes the app
// path explicitly).
import { existsSync, copyFileSync, mkdirSync, writeFileSync } from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

function setUpBareLaunch(electronDistDir) {
  // Relative from node_modules/electron/dist/resources/app/ back to the real electron/main.cjs -
  // 5 levels up (app -> resources -> dist -> electron -> node_modules) then into electron/.
  const resourcesAppDir = path.join(electronDistDir, 'resources', 'app')
  mkdirSync(resourcesAppDir, { recursive: true })
  writeFileSync(
    path.join(resourcesAppDir, 'package.json'),
    JSON.stringify({ name: 'ebiki', main: '../../../../../electron/main.cjs' }, null, 2)
  )
  console.log('[brand-electron-exe] Bare (argument-less) launches now open Ebiki instead of the Electron demo screen.')
}

async function main() {
  if (process.platform !== 'win32') return

  const electronDistDir = path.join(appRoot, 'node_modules', 'electron', 'dist')
  const electronExe = path.join(electronDistDir, 'electron.exe')
  if (!existsSync(electronExe)) {
    console.log('[brand-electron-exe] electron.exe not found (electron is optional) - skipping')
    return
  }

  try {
    setUpBareLaunch(electronDistDir)
  } catch (err) {
    console.log('[brand-electron-exe] failed to set up the bare-launch fallback (a naive taskbar pin may show the Electron demo screen):', err.message)
  }

  const icon = path.join(appRoot, 'ebiki.ico')
  if (!existsSync(icon)) {
    console.log('[brand-electron-exe] ebiki.ico not found - skipping the icon patch')
    return
  }

  let rcedit
  try {
    ;({ rcedit } = await import('rcedit'))
  } catch {
    console.log('[brand-electron-exe] rcedit not installed (optional) - skipping, taskbar icon will be the generic Electron logo')
    return
  }

  const brandedExe = path.join(electronDistDir, 'Ebiki.exe')
  try {
    copyFileSync(electronExe, brandedExe)
    await rcedit(brandedExe, {
      icon,
      'version-string': { ProductName: 'Ebiki', FileDescription: 'Ebiki' },
    })
    console.log('[brand-electron-exe] Ebiki.exe created with the Ebi icon.')
  } catch (err) {
    console.log('[brand-electron-exe] failed to brand the exe (falling back to the generic Electron icon):', err.message)
  }
}

main()
